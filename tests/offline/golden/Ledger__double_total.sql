CREATE TRIGGER "SALES"."DJTRG_DOUBLE_TOTAL_761BD"
BEFORE INSERT OR UPDATE OF "AMOUNT" ON "SALES"."LEDGER"
REFERENCING OLD ROW AS OLD NEW ROW AS NEW
FOR EACH ROW MODE DB2ROW
PROGRAM NAME LEDGDBL
WHEN (NEW.AMOUNT > 0)
BEGIN ATOMIC
DECLARE factor INTEGER;
SET factor = 2; SET NEW.total = NEW.amount * factor;
END
