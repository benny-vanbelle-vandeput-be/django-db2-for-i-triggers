CREATE TRIGGER "DJTRG_ALL_BUT_NOTE_4CC01"
BEFORE UPDATE ON "TESTAPP_ORDER"
REFERENCING OLD ROW AS OLD NEW ROW AS NEW
FOR EACH ROW MODE DB2ROW
PROGRAM NAME ORDRONLY
WHEN (OLD."ID" IS DISTINCT FROM NEW."ID" OR OLD."STATUS" IS DISTINCT FROM NEW."STATUS" OR OLD."AMOUNT" IS DISTINCT FROM NEW."AMOUNT")
BEGIN ATOMIC
SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'django_db2_for_i_triggers: Cannot update rows from testapp_order table';
END
